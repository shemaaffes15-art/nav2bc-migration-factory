from pathlib import Path

import pytest

from nav2bc.cal.parser import parse_properties, split_objects
from nav2bc.reports.analyzer import Settings, analyze_export, classify_origin

FIX = Path(__file__).parent / "fixtures"


def load(name: str) -> str:
    return (FIX / name).read_text(encoding="utf-8")


def by_id(analyses, report_id):
    return next(a for a in analyses if a.report_id == report_id)


def test_split_objects_keeps_all_object_types():
    objects = split_objects(load("export_custom_reports.txt"))
    assert [(o.object_type, o.object_id) for o in objects] == [("Table", 50010), ("Report", 50105), ("Report", 111)]
    report = objects[1]
    assert {"OBJECT-PROPERTIES", "PROPERTIES", "DATASET", "CODE", "RDLDATA"} <= set(report.sections)
    assert report.section("RDLDATA")[1].startswith("<Report")


def test_property_names_with_spaces_and_multiline_triggers():
    props = parse_properties([
        "    Modified=Yes;",
        "    Version List=NAVW19.00,MED1.00;",
        "    OnPreReport=BEGIN",
        "                  IF X = 1 THEN",
        "                    EXIT;",
        "                END;",
    ])
    assert props["Modified"] == "Yes"
    assert props["Version List"] == "NAVW19.00,MED1.00"
    assert "IF X = 1 THEN" in props["OnPreReport"]


def test_only_reports_are_analyzed():
    analyses = analyze_export(load("export_custom_reports.txt"))
    assert sorted(a.report_id for a in analyses) == [111, 50105]


def test_dataset_structure_of_custom_report():
    a = by_id(analyze_export(load("export_custom_reports.txt")), 50105)
    assert [d["name"] for d in a.dataitems] == ["Tournee", "LoopLines"]
    loop = a.dataitems[1]
    assert loop["is_integer"] and loop["parent"] == "Tournee"
    assert set(loop["triggers"]) == {"OnPreDataItem", "OnAfterGetRecord"}
    assert len(a.columns) == 6
    assert a.temporary_tables == ["TempLine"]
    assert [p["name"] for p in a.procedures] == ["BuildLines", "ExportXml"]
    assert a.dependencies["tables"] == [37, 50010, 50011]
    assert a.dependencies["codeunits"] == [50005]


def test_layout_dataset_consistency_detects_missing_and_unused_fields():
    a = by_id(analyze_export(load("export_custom_reports.txt")), 50105)
    codes = {i.code for i in a.issues}
    assert "LAYOUT_FIELD_NOT_IN_DATASET" in codes  # Line_Zone
    assert "EXPRESSION_UNKNOWN_FIELD" in codes  # LineTotal
    assert "UNUSED_COLUMNS" in codes  # Line_Weight
    # Format suffix fields generated by NAV for decimals are not errors
    assert not any("Line_AmountFormat" in i.message for i in a.issues)


def test_saas_risks_detected_from_variables_and_code():
    a = by_id(analyze_export(load("export_custom_reports.txt")), 50105)
    rules = {r["rule_id"] for r in a.risks}
    assert {"VAR-FILE", "VAR-DOTNET", "CODE-ENVIRON", "CODE-CLIENTTYPE"} <= rules
    assert all(r["validation_status"] == "to_validate" for r in a.risks)


def test_complexity_is_justified_by_factors():
    a = by_id(analyze_export(load("export_custom_reports.txt")), 50105)
    assert a.complexity_score == sum(f.points for f in a.factors)
    assert a.complexity_class == "complex"
    assert a.strategy["code"] == "txt2al_conversion"
    assert "Revue de la logique" in a.strategy["detail"]


def test_modified_standard_report_goes_to_report_extension():
    a = analyze_export(load("report_206_sales_invoice.txt"))[0]
    assert a.origin == "standard_modified"
    assert a.strategy["code"] == "report_extension"
    assert "à confirmer" in a.strategy["detail"]
    codes = {i.code for i in a.issues}
    assert {"CODE_GETDATA", "BARCODE_FONT", "UNUSED_COLUMNS"} <= codes
    assert "LAYOUT_FIELD_NOT_IN_DATASET" not in codes  # Caption / Format suffixes accepted
    assert a.rdlc["barcode_fonts"] == ["IDAutomationHC39M"]
    assert a.labels == ["InvoiceLbl", "TotalLbl"]
    assert a.request_page_fields == 1


def test_unmodified_standard_report_needs_no_migration():
    a = by_id(analyze_export(load("export_custom_reports.txt")), 111)
    assert a.origin == "standard"
    assert a.strategy["code"] == "use_standard"
    assert a.complexity_class == "simple"


def test_classic_report_is_detected():
    a = analyze_export(load("report_50120_classic_nav2009.txt"))[0]
    assert a.layouts == ["Classic"]
    assert a.classic["section_count"] == 4
    assert a.classic["control_count"] == 7
    assert a.strategy["code"] == "classic_skeleton"
    assert {"CODE-CLASSIC-SHOWOUTPUT", "CODE-CLASSIC-CREATETOTALS"} <= {r["rule_id"] for r in a.risks}


def test_word_layout_bound_fields_are_checked():
    a = analyze_export(load("report_50110_word_label.txt"))[0]
    assert a.layouts == ["Word"]
    assert a.word["decodable"] and a.word["content_controls"] == 3 and a.word["unbound_controls"] == 1
    assert a.word["bound_fields"] == ["Colis_Destinataire", "Colis_No"]
    assert a.strategy["code"] == "word_remap"
    assert [i.code for i in a.issues] == ["WORD_FIELD_NOT_IN_DATASET"]


@pytest.mark.parametrize("rid,version,modified,expected", [
    (50100, "MED1.00", True, "custom"),
    (206, "NAVW19.00,NAVFR9.00", False, "standard"),
    (206, "NAVW19.00", True, "standard_modified"),
    (206, "NAVW19.00,MED1.00", False, "standard_modified"),
    (70000120, "FLEET2.1", False, "addon"),
])
def test_origin_classification(rid, version, modified, expected):
    assert classify_origin(rid, version, modified, Settings()) == expected


def test_crlf_and_truncated_exports_are_tolerated():
    text = load("report_206_sales_invoice.txt").replace("\n", "\r\n")
    assert analyze_export(text)[0].report_id == 206
    truncated = load("export_custom_reports.txt").split("OBJECT Report 111")[0].rsplit("}", 1)[0]
    assert {a.report_id for a in analyze_export(truncated)} == {50105}
